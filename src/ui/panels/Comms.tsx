import { useEffect, useMemo, useRef, useState } from 'react'
import { searchMessages } from '../../sim/comms'
import { store, useStore } from '../store'
import { audio } from '../audio'
import { Btn, hms } from '../common'

const CH = ['SURV', 'ATC', 'PILOT', 'TANKER', 'AIRFIELD', 'INTEL', 'OPS']
export function Comms() {
  const st = useStore((s) => s.st)!
  const [q, setQ] = useState(''); const [ch, setCh] = useState<string | null>(null); const [sticky, setSticky] = useState(true)
  const [vox, setVox] = useState(audio.voiceOn)
  const box = useRef<HTMLDivElement>(null)
  const msgs = useMemo(() => searchMessages(st.messages, q, ch), [st.messages.length, q, ch, st])
  useEffect(() => { if (sticky && box.current) box.current.scrollTop = box.current.scrollHeight }, [msgs.length, sticky])
  const open = (m: (typeof msgs)[0]) => {
    if (!m.ref) return
    if (m.refKind === 'track') store.select(m.ref); else if (m.refKind === 'incident') { store.sel.incident = m.ref; store.requestPanel('incidents') }
    else if (m.refKind === 'op') store.requestPanel('ops'); else if (m.refKind === 'intel') store.requestPanel('intel'); else if (m.refKind === 'asset') { store.sel.asset = m.ref; store.requestPanel('assets') }
    else if (m.refKind === 'airfield') { store.sel.airfield = m.ref; store.requestPanel('airfields') } else if (m.refKind === 'radar') store.requestPanel('system')
  }
  return (
    <div className="col">
      <div className="toolbar">
        <input placeholder="SEARCH HISTORY (text, callsign, track, incident…)" value={q} onChange={(e) => { setQ(e.target.value); if (e.target.value) store.ui('commsSearch') }} />
        <button className={`chip ${vox ? 'on' : ''}`} onClick={() => { audio.voiceOn = !audio.voiceOn; setVox(audio.voiceOn); store.profile.settings.voice = audio.voiceOn; if (!audio.voiceOn) audio.stopAll(); store.ui('audio'); store.notify() }}>{vox ? '🔊 VOX ON' : '🔇 VOX OFF'}</button>
      </div>
      <div className="toolbar"><button className={`chip ${ch === null ? 'on' : ''}`} onClick={() => setCh(null)}>ALL</button>{CH.map((c) => <button key={c} className={`chip ${ch === c ? 'on' : ''}`} onClick={() => setCh(ch === c ? null : c)}>{c}</button>)}<span className="dim">{msgs.length}/{st.messages.length}</span></div>
      <div className="scroll msgs" ref={box} onScroll={(e) => { const t = e.currentTarget; setSticky(t.scrollTop + t.clientHeight > t.scrollHeight - 20) }}>
        {msgs.slice(-400).map((m) => <div key={m.id} className={`msg ${m.sev} ${m.ref ? 'ref' : ''}`} onClick={() => open(m)}>
          <span className="t">{hms(m.t)}</span> <span className="ch">[{m.channel}]</span> <span className="who">{m.from}→{m.to}</span> <span className="txt">{m.text}</span>
          <button className="replay" title="Replay voice" onClick={(e) => { e.stopPropagation(); audio.unlock(); audio.speak({ ...m, speak: true, sev: 'URGENT' }) }}>▶</button></div>)}
        {!msgs.length && <div className="empty">NO MESSAGES</div>}
      </div>
      <div className="dim">Every message is generated by a simulation event · {Btn.name ? '' : ''}click a message to jump to its subject</div>
    </div>
  )
}
